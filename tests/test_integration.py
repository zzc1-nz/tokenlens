    inner = patched_body.get("budget", patched_body)
    assert inner["limit_usd"] == 99.0
    assert inner["enabled"] is False

    assert client.delete(f"/api/v1/budgets/{budget_id}").status_code in (200, 204)
    assert client.get(f"/api/v1/budgets/{budget_id}").status_code == 404


