def test_full_end_to_end_story(client: TestClient, db, settings, monkeypatch):
    """The whole product narrative, in order, through the public API."""
    from tokenlens.testing import generate_workload

    with frozen_clock(monkeypatch) as anchor:
        # -- 1. ingest a realistic workload -------------------------------------------
        # Six hours of history, not just the last one: the anomaly detector's baseline
        # window is 6 x lookback, so a deployment-like dataset is what the E2E should
        # exercise (and it keeps "thin history" edge cases out of this story test).
        workload = generate_workload(count=1200, end_ms=anchor, span_minutes=360, seed=42)
        result = ingest(client, workload)
        assert result["accepted"] == 1200
        assert result["rejected"] == 0
        assert result["total_tokens"] > 0
        assert result["cost_usd"] > 0
        assert db.scalar("SELECT COUNT(*) FROM usage_snapshots") == 1200

        # Replaying the identical batch is idempotent — no double charging.
        replay = ingest(client, workload)
        assert replay["accepted"] == 0
        assert replay["duplicates"] == 1200
        assert db.scalar("SELECT COUNT(*) FROM usage_snapshots") == 1200

        # -- 2. dashboard KPIs are non-zero -------------------------------------------
        overview = get_ok(client, "/api/v1/dashboard/overview")
        kpis = overview["kpis"]
        assert kpis["today_cost_usd"] > 0
        assert kpis["today_tokens"] > 0
        assert kpis["week_cost_usd"] >= kpis["today_cost_usd"] > 0
        assert kpis["month_cost_usd"] >= kpis["week_cost_usd"] > 0
        assert kpis["active_agents"] > 0
        assert kpis["active_projects"] > 0
        assert 0 <= kpis["cache_hit_rate"] <= 1
        assert kpis["total_sessions"] > 0
        assert overview["generated_at"].endswith("Z")

        # every dashboard section has the documented shape
        for dimension in ("by_agent", "by_project", "by_model", "by_runtime"):
            assert isinstance(overview["breakdowns"][dimension], list)
            assert overview["breakdowns"][dimension], f"{dimension} should not be empty"
        assert isinstance(overview["timeseries"]["hourly"], list)
        assert isinstance(overview["timeseries"]["daily"], list)
        assert overview["budgets"] == []
        assert "summary" in overview["alerts"]
        assert "summary" in overview["anomalies"]

        # -- 3. create a deliberately tight budget ------------------------------------
        spent_today = get_ok(client, "/api/v1/usage/summary")["totals"]["cost_usd"]
        assert spent_today > 0
        limit = round(max(0.01, spent_today * 0.4), 6)
        created = client.post(
            "/api/v1/budgets",
            json={
                "name": "e2e-daily",
                "scope": "global",
                "scope_key": "*",
                "period": "daily",
                "limit_usd": limit,
                "thresholds": [0.5, 0.8, 1.0],
                "desktop": True,
                "enabled": True,
            },
        )
        assert created.status_code in (200, 201), created.text
        budget = created.json()
        budget_id = budget["id"] if "id" in budget else budget["budget"]["id"]
        assert budget_id > 0
        assert db.scalar("SELECT COUNT(*) FROM budgets") == 1

        # -- 4. evaluation fires alerts -----------------------------------------------
        first = client.post("/api/v1/budgets/evaluate")
        assert first.status_code == 200, first.text
        first_body = first.json()
        assert first_body["evaluated"] >= 1
        assert first_body["dry_run"] is False
        triggered = first_body["triggered"]
        assert triggered, "a budget exceeded by 2.5x must fire at least one threshold"

        # Every emitted alert is above its threshold and carries the overspend.
        for alert in triggered:
            assert alert["budget_id"] == budget_id
            assert alert["severity"] in {"warning", "critical", "exceeded"}
            assert alert["spent_usd"] > alert["limit_usd"] * alert["threshold"]
            assert alert["overspend_usd"] == pytest.approx(
                max(0.0, alert["spent_usd"] - alert["limit_usd"]), abs=1e-6
            )
        assert any(alert["severity"] == "exceeded" for alert in triggered)

        # Re-evaluating must NOT duplicate rows — it increments trigger_count instead.
        second = client.post("/api/v1/budgets/evaluate")
        assert second.status_code == 200, second.text
        assert len(second.json()["triggered"]) == len(triggered)

        alerts_body = get_ok(client, "/api/v1/alerts", limit=50)
        assert alerts_body["total"] == len(triggered)
        assert alerts_body["items"]
        for alert in alerts_body["items"]:
            assert alert["trigger_count"] >= 2, "second evaluation must bump the trigger count"
            assert alert["created_at"].endswith("Z")
            assert isinstance(alert["channels"], list)
        # newest first
        ids = [alert["id"] for alert in alerts_body["items"]]
        assert ids == sorted(ids, reverse=True)

        summary = get_ok(client, "/api/v1/alerts/summary")
        assert summary["total_alerts"] == len(triggered)
        assert summary["total_triggers"] >= len(triggered)
        assert summary["total_overspend_usd"] > 0
        assert summary["by_severity"]
        assert summary["by_budget"]
        assert summary["by_budget"][0]["triggers"] >= 1
        assert summary["last_triggered_at"].endswith("Z")

        # -- 5. budgets are exposed with an evaluated status --------------------------
        budgets_body = get_ok(client, "/api/v1/budgets")
        assert len(budgets_body["items"]) == 1
        status = budgets_body["items"][0]
        assert status["status"] in {"warning", "critical", "exceeded"}
        assert status["pct"] > 1.0
        assert status["triggered_thresholds"]
        assert status["trigger_count"] >= 2
        assert status["overspend_usd"] > 0
        assert status["budget"]["name"] == "e2e-daily"

        # -- 6. inject an incident and detect it --------------------------------------
        incident = _incident_snapshots(anchor)
        incident_result = ingest(client, incident)
        assert incident_result["accepted"] == len(incident)

        detect = client.post("/api/v1/anomalies/detect", params={"lookback_minutes": 60})
        assert detect.status_code == 200, detect.text
        detect_body = detect.json()
        assert detect_body["scanned_agents"] >= 1
        detected = detect_body["detected"]
        assert detected, "the injected retry/context/tool incident must be detected"

        reasons = set()
        for event in detected:
            assert event["reason"] in ANOMALY_REASONS
            assert event["reason_label"] == REASON_LABELS[event["reason"]]
            assert event["severity"] in {"low", "medium", "high", "critical"}
            assert event["status"] == "open"
            assert event["metric"] == "tokens_per_min"
            assert event["score"] > 0
            assert event["observed"] > 0
            assert event["baseline"] >= 0
            # §4 defines ratio = observed / baseline. Where the baseline is non-zero the
            # identity must hold exactly; a zero baseline makes the quotient undefined and
            # §8.4's ratio guard vacuous, so that case is deliberately not asserted here.
            if event["baseline"] > 0:
                assert event["ratio"] == pytest.approx(
                    event["observed"] / event["baseline"], rel=1e-2
                ), f"ratio must be observed/baseline: {event}"
                # §8.3 only flags when observed >= 3 x baseline.
                assert event["ratio"] >= 3.0
            assert isinstance(event["evidence"], dict) and event["evidence"]
            assert event["evidence"]["observed_p95"] == pytest.approx(event["observed"], rel=1e-3)
            assert event["window_start"].endswith("Z") and event["window_end"].endswith("Z")
            assert event["detected_at"].endswith("Z")
            assert event["fingerprint"]
            assert event["cost_usd"] >= 0
            reasons.add(event["reason"])

        # The three injected signatures are the ones the classifier must find.
        injected = {"retry_storm", "context_bloat", "uncompressed_tool_output"}
        assert injected <= reasons, f"missing injected root causes: {sorted(injected - reasons)}"

        # Each injected agent is classified with its own signature (no cross-talk).
        by_agent = {event["agent"]: event["reason"] for event in detected}
        assert by_agent.get("incident-retry") == "retry_storm"
        assert by_agent.get("incident-context") == "context_bloat"
        assert by_agent.get("incident-tool") == "uncompressed_tool_output"

        # Detection is idempotent per fingerprint bucket.
        again = client.post("/api/v1/anomalies/detect", params={"lookback_minutes": 60})
        assert again.status_code == 200, again.text
        assert len(again.json()["detected"]) <= len(detected)

        # -- 7. anomaly list, summary, status transitions -----------------------------
        listed = get_ok(client, "/api/v1/anomalies", limit=50)
        assert listed["total"] >= len(detected)
        assert listed["items"]
        assert listed["items"][0]["detected_at"].endswith("Z")

        anomaly_summary = get_ok(client, "/api/v1/anomalies/summary")
        assert anomaly_summary["total_events"] >= len(detected)
        assert anomaly_summary["open_events"] >= 1
        assert anomaly_summary["by_reason"]
        assert set(anomaly_summary["by_reason"]) <= ANOMALY_REASONS
        assert anomaly_summary["estimated_waste_usd"] >= 0
        assert anomaly_summary["last_detected_at"].endswith("Z")

        target = listed["items"][0]
        patched = client.patch(f"/api/v1/anomalies/{target['id']}", json={"status": "resolved"})
        assert patched.status_code == 200, patched.text
        assert patched.json()["status"] == "resolved"
        assert get_ok(client, "/api/v1/anomalies", status="resolved")["total"] >= 1
        assert client.patch("/api/v1/anomalies/999999", json={"status": "resolved"}).status_code == 404
        assert client.patch(f"/api/v1/anomalies/{target['id']}", json={"status": "nope"}).status_code == 422

        # -- 8. CSV export -------------------------------------------------------------
        export = client.get(
            "/api/v1/export/csv",
            params={
                "dataset": "timeseries",
                "bucket": "hour",
                "from": timeutil.iso(anchor - 24 * 3_600_000),
                "to": timeutil.iso(anchor),
            },
        )
        assert export.status_code == 200, export.text
        assert "text/csv" in export.headers["content-type"]
        assert "charset=utf-8" in export.headers["content-type"].lower()
        disposition = export.headers["content-disposition"]
        assert "attachment" in disposition
        assert "tokenlens-timeseries-" in disposition
        assert export.content.startswith(b"\xef\xbb\xbf"), "Excel needs a UTF-8 BOM"

        rows = list(csv.reader(io.StringIO(export.content.decode("utf-8-sig"))))
        assert len(rows) >= 2, "the export should contain a header and at least one data row"
        header = rows[0]
        assert header, "CSV must have a header row"
        for column in header:
            assert column == column.lower()
            assert " " not in column, "headers must be snake_case"
        assert any("cost" in column for column in header)
        assert any("token" in column for column in header)

        # -- 9. the dashboard is still coherent after all of that ---------------------
        final_overview = get_ok(client, "/api/v1/dashboard/overview")
        assert final_overview["budgets"], "the created budget must appear on the dashboard"
        assert final_overview["alerts"]["recent"], "recent alerts feed the overview panel"
        assert final_overview["anomalies"]["recent"], "recent anomalies feed the overview panel"
        assert final_overview["anomalies"]["summary"]["total_events"] >= 1

        # ... and every page of the UI is served.
        assert client.get("/").status_code == 200
        assert client.get("/static/app.js").status_code == 200
        assert client.get("/static/styles.css").status_code == 200


