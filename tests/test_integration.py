"""End-to-end integration tests — the TokenLens story through the public HTTP API.

The suite walks the product exactly the way a user would, against a real ASGI app bound to
an isolated SQLite file:

    ingest a realistic workload
        -> dashboard KPIs light up
        -> create a tight budget -> evaluate -> alerts fire with trigger counts + overspend
        -> inject an incident -> detect anomalies -> classify root cause -> acknowledge
        -> export CSV (BOM + snake_case headers)
        -> lock the deployment down with an API key and watch unauthenticated calls fail

Determinism: every test freezes ``tokenlens.timeutil.now_ms`` to a fixed instant, so the
"current" daily/weekly/monthly windows never straddle a midnight boundary mid-run. The
workload itself is generated by :func:`tokenlens.testing.generate_workload` with a fixed
seed.
"""

from __future__ import annotations

import contextlib
import csv
import io
import sys
from typing import Iterator

import pytest
from fastapi.testclient import TestClient

from tokenlens import timeutil
from tokenlens.testing import make_snapshot

# 2026-11-10T12:00:00Z == 20:00 Asia/Shanghai — comfortably inside one calendar day.
ANCHOR_MS = timeutil.parse_time_ms("2026-11-10T12:00:00Z")

ANOMALY_REASONS = {
    "retry_storm",
    "context_bloat",
    "uncompressed_tool_output",
    "cache_miss_storm",
    "traffic_spike",
    "unknown",
}

REASON_LABELS = {
    "retry_storm": "重试风暴",
    "context_bloat": "上下文膨胀",
    "uncompressed_tool_output": "工具返回数据未压缩",
    "cache_miss_storm": "缓存命中崩塌",
    "traffic_spike": "流量尖峰",
    "unknown": "未知",
}


