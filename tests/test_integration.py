def test_csv_export_covers_every_dataset(client: TestClient, monkeypatch):
    from tokenlens.testing import generate_workload

    with frozen_clock(monkeypatch) as anchor:
        ingest(client, generate_workload(count=120, end_ms=anchor, span_minutes=60, seed=5))
        window = {
            "from": timeutil.iso(anchor - 24 * 3_600_000),
            "to": timeutil.iso(anchor),
        }
        for dataset in ("timeseries", "breakdown", "sessions", "snapshots"):
            response = client.get("/api/v1/export/csv", params={"dataset": dataset, **window})
            assert response.status_code == 200, f"{dataset}: {response.text}"
            assert "text/csv" in response.headers["content-type"]
            assert response.content.startswith(b"\xef\xbb\xbf")
            assert f"tokenlens-{dataset}-" in response.headers["content-disposition"]
            rows = list(csv.reader(io.StringIO(response.content.decode("utf-8-sig"))))
            assert rows and rows[0], f"{dataset} export has no header"

        # An unknown dataset is a client error. The contract pins Pydantic *schema*
        # violations to 422; a hand-validated query value may legitimately be a 400
        # (that is what the ValueError handler in app.py produces), so accept both.
        bad_dataset = client.get("/api/v1/export/csv", params={"dataset": "nope"})
        assert bad_dataset.status_code in (400, 422), bad_dataset.text
        assert "detail" in bad_dataset.json()


