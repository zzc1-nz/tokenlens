@contextlib.contextmanager
def frozen_clock(monkeypatch: pytest.MonkeyPatch, anchor_ms: int = ANCHOR_MS) -> Iterator[int]:
    """Pin ``now_ms()`` for every TokenLens module for the duration of the block.

    Modules may either call ``timeutil.now_ms()`` or bind the function directly
    (``from .timeutil import now_ms``); both styles are patched so the budget window,
    the dashboard KPIs and the anomaly lookback all agree on "now".
    """
    original = timeutil.now_ms
    monkeypatch.setattr(timeutil, "now_ms", lambda: anchor_ms)
    for module_name, module in list(sys.modules.items()):
        if not module_name.startswith("tokenlens") or module_name == "tokenlens.timeutil":
            continue
        if getattr(module, "now_ms", None) is original:
            monkeypatch.setattr(module, "now_ms", lambda: anchor_ms)
    yield anchor_ms


def payload(snapshots) -> dict:
    """Serialise ``SnapshotIn`` objects into the ingest request body."""
    return {"snapshots": [snapshot.model_dump() for snapshot in snapshots]}


def ingest(client: TestClient, snapshots, *, chunk: int = 500) -> dict:
    """POST snapshots in batches (the API caps a batch at ``max_ingest_batch``)."""
    totals = {"accepted": 0, "duplicates": 0, "rejected": 0, "total_tokens": 0, "cost_usd": 0.0}
    for start in range(0, len(snapshots), chunk):
        batch = snapshots[start : start + chunk]
        response = client.post("/api/v1/ingest/snapshots", json=payload(batch))
        assert response.status_code == 200, response.text
        body = response.json()
        for key in ("accepted", "duplicates", "rejected", "total_tokens"):
            totals[key] += body[key]
        totals["cost_usd"] += body["cost_usd"]
    return totals


def get_ok(client: TestClient, path: str, **params) -> dict:
    response = client.get(path, params={k: v for k, v in params.items() if v is not None})
    assert response.status_code == 200, f"{path} -> {response.status_code}: {response.text}"
    return response.json()


def _incident_snapshots(anchor_ms: int) -> list:
    """Three agents, one per anomaly signature, each with a quiet baseline then a burst.

    The detector compares the trailing lookback window against a *median/MAD* baseline
    taken from the hours before it, so each incident agent first needs history that looks
    boring — then a burst that is obviously not.

    The signatures are kept mutually exclusive so the classifier's documented branch order
    (§8.4) cannot mask a signature behind an earlier rule:

    * ``incident-retry``   — retries/requests = 0.8, everything else boring
    * ``incident-context`` — context_window = 1M, no retries, modest tool output
    * ``incident-tool``    — tool_result_bytes/request = 600 KB, *small* prompts so the
      "avg input per request >= 3x baseline" branch of ``context_bloat`` cannot fire first
    """
    # agent -> (project, model, requests, retries, input, output, context_window, tool_bytes)
    burst_profiles = {
        "incident-retry": ("payments-api", "gpt-5", 10, 8, 48_000, 9_000, 64_000, 4_000),
        "incident-context": ("ml-pipeline", "claude-opus-4-1", 10, 0, 48_000, 9_000, 1_000_000, 4_000),
        "incident-tool": ("infra-tools", "deepseek-chat", 10, 0, 2_000, 9_000, 64_000, 6_000_000),
    }

    snapshots = []

    # -- baseline: 5 hours of quiet traffic, ending 70 minutes before "now" -------------
    baseline_start = anchor_ms - 5 * 3_600_000
    baseline_end = anchor_ms - 70 * 60_000
    step_ms = 60_000
    cursor = baseline_start
    index = 0
    while cursor < baseline_end:
        for agent, (project, model, *_rest) in burst_profiles.items():
            snapshots.append(
                make_snapshot(
                    ts=cursor,
                    agent=agent,
                    project=project,
                    model=model,
                    session_id=f"{agent}-base",
                    input_tokens=400,
                    output_tokens=120,
                    cache_read_tokens=800,
                    cache_write_tokens=0,
                    requests=4,
                    retries=0,
                    tool_calls=1,
                    context_window=64_000,
                    tool_result_bytes=2_000,
                    event_id=f"{agent}-base-{index}",
                )
            )
        cursor += step_ms
        index += 1

    # -- burst: 20 minutes of heavy traffic ending at "now" ----------------------------
    burst_start = anchor_ms - 20 * 60_000
    for minute in range(20):
        ts = burst_start + minute * 60_000
        for agent, profile in burst_profiles.items():
            project, model, requests, retries, input_tokens, output_tokens, context_window, tool_bytes = profile
            for sub in range(4):
                snapshots.append(
                    make_snapshot(
                        ts=ts + sub * 12_000,
                        agent=agent,
                        project=project,
                        model=model,
                        session_id=f"{agent}-burst-{minute}",
                        input_tokens=input_tokens,
                        output_tokens=output_tokens,
                        cache_read_tokens=1_000,
                        cache_write_tokens=0,
                        requests=requests,
                        retries=retries,
                        tool_calls=6,
                        context_window=context_window,
                        tool_result_bytes=tool_bytes,
                        event_id=f"{agent}-burst-{minute}-{sub}",
                    )
                )
    return snapshots


