def test_api_key_mode_rejects_unauthenticated_requests(settings, db):
    """With TOKENLENS_API_TOKEN set, every /api/v1 route (except probes) needs the key."""
    from tokenlens.app import create_app

    settings.api_token = "s3cret"
    application = create_app(settings=settings, db=db)
    with TestClient(application) as secured:
        # Probes and the dashboard shell stay open.
        assert secured.get("/health").status_code == 200
        assert secured.get("/api/v1/meta").status_code == 200
        assert secured.get("/").status_code == 200
        assert secured.get("/static/app.js").status_code == 200

        for path in (
            "/api/v1/dashboard/overview",
            "/api/v1/usage/summary",
            "/api/v1/trends",
            "/api/v1/budgets",
            "/api/v1/alerts",
            "/api/v1/alerts/summary",
            "/api/v1/anomalies",
            "/api/v1/anomalies/summary",
            "/api/v1/export/csv?dataset=timeseries",
        ):
            assert secured.get(path).status_code == 401, f"{path} must require X-API-Key"
            assert secured.get(path, headers={"X-API-Key": "s3cret"}).status_code == 200
            assert secured.get(path, headers={"X-API-Key": "wrong"}).status_code == 401

        # Writes are guarded too.
        assert secured.post("/api/v1/ingest/snapshots", json=payload([make_snapshot()])).status_code == 401
        assert secured.post("/api/v1/budgets/evaluate").status_code == 401
        assert secured.post("/api/v1/anomalies/detect").status_code == 401


def test_ingest_batch_limits_and_validation(client: TestClient):
    """Contract guards the UI depends on: batch size, negative tokens, bad timestamps."""
    too_many = [make_snapshot(event_id=f"big-{i}") for i in range(5001)]
